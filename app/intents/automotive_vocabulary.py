def render_automotive_vocabulary() -> str:
    """Devuelve el vocabulario en un formato compacto para el prompt."""
    lines = []
    for intent, keywords in AUTOMOTIVE_INTENT_KEYWORDS.items():
        lines.append(f"- {intent.value}: {', '.join(keywords)}")
    lines.append("\nENTIDADES Y EXPRESIONES:")
    for entity, keywords in AUTOMOTIVE_ENTITY_VOCABULARY.items():
        lines.append(f"- {entity}: {', '.join(keywords)}")
    return "\n".join(lines)


def render_automotive_context_rules() -> str:
    """Devuelve reglas de contexto para resolver expresiones ambiguas."""
    return "\n".join(f"- {rule}" for rule in AUTOMOTIVE_CONTEXT_RULES)
